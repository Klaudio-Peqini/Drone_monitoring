"""Solve actual 3-D fields and save uniform physical-time snapshots."""
import csv
import json
import time
from pathlib import Path
import numpy as np
from scipy.fft import set_workers
from .config import validate, rotor_kwargs
from .grid import Grid, cell_velocity
from .flow import Flow
from .rotor import Rotor

MARKER = 'drone_airflow3d_case'


def output_folder(path, overwrite=False):
    p = Path(path)
    if p.exists() and any(p.iterdir()):
        if not overwrite or not (p / MARKER).is_file():
            raise ValueError('Output folder is nonempty. Choose a new folder or use --overwrite on a package-owned result.')
        # Only replace files created by this package; preserve unrelated files.
        for name in ('snapshots.npz', 'config.json', 'summary.json', 'history.csv',
                     'flow_3d.gif', 'flow_3d.png', 'particles_3d.gif', 'particles_3d.png',
                     'render_summary.json'):
            (p / name).unlink(missing_ok=True)
    p.mkdir(parents=True, exist_ok=True)
    (p / MARKER).write_text('Generated by Drone Airflow 3D\n')
    return p


def simulate(config, folder, threads=1, overwrite=False):
    c = validate(config)
    g = Grid(c['grid'], c['bounds_m'])
    rotors = [Rotor(g, **rotor_kwargs(r)) for r in c['rotors']]
    f = Flow(g, nu=c['nu_m2_s'], rho=c['rho_kg_m3'], cfl=c['cfl'])
    p = output_folder(folder, overwrite)
    (p / 'config.json').write_text(json.dumps(c, indent=2) + '\n')
    times = np.linspace(0., c['duration_s'], c['frames'])
    fields = {k: np.empty((len(times), *g.shape), dtype=np.float32) for k in ('u', 'v', 'w', 'p')}
    rows = []
    errors = dict(max_divergence_1_s=0., max_thrust_error_N=0., max_torque_error_Nm=0.)
    steps = 0
    dtmin = float('inf'); dtmax_actual = 0.
    limit = min(c['max_dt_s'], np.deg2rad(c['blade_step_deg']) / max(r.omega for r in rotors),
                .5 * min(g.h) / max(r.omega*r.R for r in rotors))
    start = time.perf_counter()

    def acceleration(t):
        total = g.faces()
        for r in rotors:
            force = r.acceleration(t, f.rho)
            for a in range(3):
                total[a] += force[a]
        return total

    def record(i):
        for k, q in zip(('u', 'v', 'w'), cell_velocity(f.vel)):
            fields[k][i] = q
        fields['p'][i] = f.p
        row = dict(frame=i, step=steps, **f.diagnostics())
        row['applied_thrust_N'] = sum(r.last.get('applied_thrust_N', 0.) for r in rotors)
        rows.append(row)

    record(0)
    with set_workers(threads):
        for i, target in enumerate(times[1:], 1):
            while f.time < target - 1e-13:
                bound = min(limit, target - f.time)
                acc = acceleration(f.time + .5*bound)
                dt = f.stable_dt(bound, acc)
                if dt < bound:
                    acc = acceleration(f.time + .5*dt)
                    # Ramping loads are monotone; the earlier midpoint cannot
                    # increase the force-based restriction.
                if dt < 1e-12:
                    raise FloatingPointError('Time step collapsed; result not accepted')
                f.step(dt, acc)
                steps += 1
                dtmin = min(dtmin, dt); dtmax_actual = max(dtmax_actual, dt)
                d = f.diagnostics()
                errors['max_divergence_1_s'] = max(errors['max_divergence_1_s'], d['max_divergence_1_s'])
                for r in rotors:
                    errors['max_thrust_error_N'] = max(errors['max_thrust_error_N'], abs(r.last['requested_thrust_N']-r.last['applied_thrust_N']))
                    errors['max_torque_error_Nm'] = max(errors['max_torque_error_Nm'], abs(r.last['requested_torque_Nm']-r.last['applied_torque_Nm']))
                if d['max_divergence_1_s']*dt > 1e-8:
                    raise FloatingPointError('Pressure projection gate failed')
            record(i)
            if i % max(1, (len(times)-1)//5) == 0 or i == len(times)-1:
                print(f'Solving 3-D: {target:.3f}/{c["duration_s"]:.3f} s', flush=True)
    np.savez_compressed(p / 'snapshots.npz', times=times, x=g.axes[0], y=g.axes[1], z=g.axes[2], **fields)
    with (p / 'history.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0])); writer.writeheader(); writer.writerows(rows)
    summary = dict(status='PASS: numerical gates only', model='3-D incompressible MAC projection; prescribed-load rotating actuator lines',
                   backend='NumPy momentum and forcing; SciPy FFT pressure', threads=threads,
                   steps=steps, frames=len(times), simulation_time_s=float(f.time),
                   solve_wall_seconds=time.perf_counter()-start, time_step_min_s=dtmin, time_step_max_s=dtmax_actual,
                   grid=c['grid'], smoothing_to_radius=[r.epsilon/r.R for r in rotors],
                   **errors, final=f.diagnostics(),
                   limitations=['Illustrative rotor loads and geometry; not DJI blade geometry.',
                                'No experimental validation, turbulence closure, pollutant transport, ground or fuselage.',
                                'Thrust and torque are inputs. RPM does not predict either.',
                                'Float64 solver; float32 saved cell-centre fields; no restart state.'])
    (p / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    return summary
